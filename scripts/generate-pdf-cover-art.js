/**
 * Generates lib/pdf/cover-art.ts from assets/images/splash-background.svg: the artwork behind the
 * cover page of an exported collection PDF.
 *
 * The splash SVG is imported as a component in the app (see metro.config.js), so the PDF, which is
 * built from an HTML string, cannot read it as a file. This script turns it into a string instead.
 * It also drops the rounded phone corners, makes the artwork fill its box (like resizeMode "cover"), and removes the
 * beads logo and the "My Dua Collection" title that are drawn into the splash artwork: the PDF draws those itself, in
 * real text, so the collection name can go underneath.
 *
 * Run it again after changing the splash artwork:  node scripts/generate-pdf-cover-art.js
 */
/* global __dirname */
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const source = path.join(root, 'assets/images/splash-background.svg')
const outFile = path.join(root, 'lib/pdf/cover-art.ts')

let svg = fs.readFileSync(source, 'utf8').trim()

// the page is a plain rectangle: no rounded phone corners on the outer shape
svg = svg.replace(/(<rect width="375" height="690") rx="43"/g, '$1')
svg = svg.replace(/(<clipPath id="clip0_[^"]+">\s*<rect width="375" height="690") rx="43"/g, '$1')

// the logo (gold) and the title (white) are the only long single paths in the artwork
svg = svg.replace(/<path\b[^>]*\/>/g, (tag) => (tag.length > 5000 ? '' : tag))

// fill the page box, cropping the sides or the top and bottom instead of stretching
svg = svg.replace(
  /<svg width="375" height="690" viewBox="0 0 375 690"/,
  '<svg width="100%" height="100%" viewBox="0 0 375 690" preserveAspectRatio="xMidYMid slice"',
)
if (!svg.includes('preserveAspectRatio="xMidYMid slice"')) throw new Error('Could not find the <svg> tag to adjust')

const body = `/**
 * GENERATED by scripts/generate-pdf-cover-art.js from assets/images/splash-background.svg. Do not edit by hand.
 * The artwork behind the cover page of an exported collection PDF (375 x 690, scaled to fill the page).
 */
export const COVER_ART_SVG = ${JSON.stringify(svg)}
`
fs.writeFileSync(outFile, body)
console.log(`Wrote ${path.relative(root, outFile)} (${Math.round(body.length / 1024)} KB)`)
