/**
 * Generates components/icons/collection-icons/line-icons.tsx from the stroke-style SVGs in
 * assets/icons/collection/.
 *
 * To add a new icon: drop the .svg into assets/icons/collection/, add its file name (no
 * extension) to LINE_ICONS below, then run:  node scripts/generate-line-icons.js
 */
const fs = require('fs')
const path = require('path')

const LINE_ICONS = [
  'chat-sparkle',
  'star-pillars',
  'open-book',
  'moon-sparkle',
  'kaaba',
  'crescent-cup',
  'cupping-cup',
  'heart-check',
  'checklist',
]

const root = path.join(__dirname, '..')
const svgDir = path.join(root, 'assets/icons/collection')
const outFile = path.join(root, 'components/icons/collection-icons/line-icons.tsx')

const defs = LINE_ICONS.map((name) => {
  const svg = fs.readFileSync(path.join(svgDir, `${name}.svg`), 'utf8')
  const [, w, h] = svg.match(/<svg[^>]*width="([\d.]+)"[^>]*height="([\d.]+)"/)
  const paths = [...svg.matchAll(/<path ([^>]*?)\/>/g)].map(([, attrs]) => ({
    d: attrs.match(/\bd="([^"]+)"/)[1],
    sw: (attrs.match(/stroke-width="([\d.]+)"/) || [, '1'])[1],
    round: attrs.includes('stroke-linecap="round"'),
  }))
  return { name, w, h, paths }
})

const body = defs
  .map(
    ({ name, w, h, paths }) =>
      `  '${name}': {\n    w: ${w},\n    h: ${h},\n    paths: [\n` +
      paths
        .map((p) => `      { d: '${p.d}', sw: ${p.sw}${p.round ? ', round: true' : ''} },\n`)
        .join('') +
      `    ],\n  },\n`
  )
  .join('')

const file = `// AUTO-GENERATED by scripts/generate-line-icons.js from assets/icons/collection/*.svg
// Do not edit by hand – change the .svg and re-run the script.
import React from 'react'
import Svg, { Path } from 'react-native-svg'

export const LINE_ICON_KEYS = [
${LINE_ICONS.map((n) => `  '${n}',`).join('\n')}
] as const

export type LineIconKey = (typeof LINE_ICON_KEYS)[number]

interface LineIconDef {
  w: number
  h: number
  paths: { d: string; sw: number; round?: boolean }[]
}

const LINE_ICONS: Record<LineIconKey, LineIconDef> = {
${body}}

export const isLineIconKey = (name: string): name is LineIconKey =>
  (LINE_ICON_KEYS as readonly string[]).includes(name)

/** Longest side of the exported SVG, e.g. 30 – pass as \`size\` to render it exactly as designed. */
export const lineIconNativeSize = (name: LineIconKey) =>
  Math.max(LINE_ICONS[name].w, LINE_ICONS[name].h)

// Extra canvas so thick strokes at the artwork edges never get clipped
const PAD = 1

interface LineIconProps {
  name: LineIconKey
  color: string
  /** Length of the icon's longest side in px. */
  size: number
  /** Multiplies the stroke width (1 = as designed). */
  thickness?: number
}

export function LineIcon({ name, color, size, thickness = 1 }: LineIconProps) {
  const { w, h, paths } = LINE_ICONS[name]
  const scale = size / Math.max(w, h)
  return (
    <Svg
      width={(w + PAD * 2) * scale}
      height={(h + PAD * 2) * scale}
      viewBox={\`\${-PAD} \${-PAD} \${w + PAD * 2} \${h + PAD * 2}\`}
      fill='none'
    >
      {paths.map((p, i) => (
        <Path
          key={i}
          d={p.d}
          stroke={color}
          strokeWidth={p.sw * thickness}
          strokeLinecap={p.round ? 'round' : undefined}
          strokeLinejoin={p.round ? 'round' : undefined}
        />
      ))}
    </Svg>
  )
}
`

fs.writeFileSync(outFile, file)
console.log(`Wrote ${path.relative(root, outFile)} (${defs.length} icons)`)
